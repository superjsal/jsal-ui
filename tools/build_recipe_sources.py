"""Builds jsalUI/Professions/RecipeSources.lua: where each recipe comes from, by name.

From data/professions/wowhead-sources.json (read from Wowhead Forever with tools/wowhead/recipes.js:
the recipe lists, and every vendor's page) and the game's own tables for which spell a pattern
teaches (matched by name inside its profession, as build_professions.py does).

Run: python -I tools/build_recipe_sources.py
"""

import csv
import json
import pathlib
import re
import sys

# python -I leaves this folder off the path, so it's put there for maps.py.
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
from maps import forever_spot  # noqa: E402

ROOT = pathlib.Path(__file__).resolve().parent.parent
SPELLS = ROOT / "data" / "spells"
SRC = ROOT / "data" / "professions" / "wowhead-sources.json"
OUT = ROOT / "jsalUI" / "Professions" / "RecipeSources.lua"

LINES = {"alchemy": 171, "blacksmithing": 164, "enchanting": 333, "engineering": 202, "leatherworking": 165,
         "tailoring": 197, "cooking": 185, "first-aid": 129}
# Vendors Wowhead places at a dungeon entrance with no zone: the zone they stand in.
ZONE_FIX = {5783: 17, 2683: 1}
PATTERN = re.compile(r"^(Pattern|Recipe|Plans|Schematic|Formula|Manual|Design): (.+)$")


def rows(name):
    with open(SPELLS / f"{name}.csv", newline="", encoding="utf-8") as f:
        return list(csv.DictReader(f))


def lua_string(text):
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def side(react):
    """1 Alliance, 2 Horde, 0 both or unknown, from Wowhead's [alliance, horde] reaction."""
    a = len(react) > 0 and react[0] is not None and react[0] >= 0
    h = len(react) > 1 and react[1] is not None and react[1] >= 0
    if a and not h:
        return 1
    if h and not a:
        return 2
    return 0


def main():
    data = json.loads(SRC.read_text(encoding="utf-8"))
    names = {int(r["ID"]): r["Name_lang"] for r in rows("SpellName")}
    by_name = {}
    for r in rows("SkillLineAbility"):
        line, spell = int(r["SkillLine"]), int(r["Spell"])
        if spell in names:
            by_name.setdefault((line, names[spell]), spell)

    quests = data.get("quests", {})
    sellers = {}
    for npc_id, npc in data["npcs"].items():
        for item, sale in npc["sells"].items():
            sellers.setdefault(int(item), []).append((int(npc_id), sale))

    recipes, used, unmatched = {}, set(), 0
    counts = {"vendor": 0, "quest": 0, "mob": 0, "world": 0}
    for prof, items in data["lists"].items():
        for item, name, _skill, source, more in items:
            m = PATTERN.match(name)
            spell = m and by_name.get((LINES[prof], m.group(2)))
            if not spell:
                unmatched += 1
                continue
            entry = recipes.setdefault(spell, {})
            vendors = sorted(sellers.get(item, []))
            if vendors:
                flat = []
                for npc_id, sale in vendors:
                    flat += [npc_id, sale[0], max(0, sale[1])]
                    used.add(npc_id)
                entry["v"] = flat
            vendor_ids = {npc_id for npc_id, _ in vendors}
            for n, kind, ident, zone, category in more:
                if kind == 5 and n and "q" not in entry:
                    quest = quests.get(str(ident)) or [0, 0, 0]
                    entry["q"] = (n, category if category > 0 else 0, quest[0] if quest[0] in (1, 2) else 0)
                elif kind in (1, 2) and n and ident not in vendor_ids and 2 in source and "d" not in entry:
                    entry["d"] = (n, zone)
            if 2 in source and "d" not in entry:
                entry["w"] = True
            if not entry:
                del recipes[spell]

    for entry in recipes.values():
        for key, label in (("v", "vendor"), ("q", "quest"), ("d", "mob"), ("w", "world")):
            if key in entry:
                counts[label] += 1

    lines = [
        "-- Where each recipe comes from, by name: who sells it and for how much, the",
        "-- quest that gives it, the mob that drops it. From Wowhead's WoW Forever",
        f"-- recipe lists and vendor pages (read {data.get('fetched', '?')}); regenerated by the build,",
        "-- not by hand.",
        "local _, ns = ...",
        "",
        "ns.RecipeSources = {",
        "    -- A vendor: name, zone (area ID), side (1 Alliance, 2 Horde, 0 both), then",
        "    -- the map and the spot they stand on (0 to 100), when known.",
        "    npcs = {",
    ]
    for npc_id in sorted(used):
        npc = data["npcs"][str(npc_id)]
        zone = ZONE_FIX.get(npc_id) or (npc["loc"][0] if npc["loc"] else 0)
        parts = [lua_string(npc["n"]), str(zone), str(side(npc["react"]))]
        if len(npc["spot"]) == 3 and npc["spot"][0]:
            # Wowhead's spot is on Classic's map; Forever draws a few zones differently.
            spot_x, spot_y = forever_spot(npc["spot"][0], npc["spot"][1], npc["spot"][2])
            parts += [str(npc["spot"][0]), f"{spot_x:g}", f"{spot_y:g}"]
        lines.append(f"        [{npc_id}] = {{ " + ", ".join(parts) + " },")
    lines += [
        "    },",
        "    -- A recipe, by its spell: v its vendors (vendor, price in copper, how many",
        "    -- in stock or 0 for always), q its quest, zone and side, d the one mob or chest",
        "    -- that drops it and its zone, w when it drops from many.",
        "    recipes = {",
    ]
    for spell in sorted(recipes):
        entry, parts = recipes[spell], []
        if "v" in entry:
            parts.append("v = { " + ", ".join(str(x) for x in entry["v"]) + " }")
        if "q" in entry:
            parts.append(f"q = {{ {lua_string(entry['q'][0])}, {entry['q'][1]}, {entry['q'][2]} }}")
        if "d" in entry:
            parts.append(f"d = {{ {lua_string(entry['d'][0])}, {entry['d'][1]} }}")
        if "w" in entry:
            parts.append("w = true")
        lines.append(f"        [{spell}] = {{ " + ", ".join(parts) + " },")
    lines += ["    },", "}", ""]
    OUT.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"-> {OUT.relative_to(ROOT)} ({OUT.stat().st_size // 1024} KB)")
    print(f"  {len(recipes)} recipes, {len(used)} vendors; {unmatched} list items matched no recipe")
    print("  " + ", ".join(f"{k} {v}" for k, v in counts.items()))


if __name__ == "__main__":
    main()
