"""Builds jsalUI/Training/TameData.lua: which beasts a hunter can tame carry which pet ability
ranks, from Wowhead Forever (data/pets/wowhead.json, read in the browser pane with
tools/wowhead/petspells.py and tools/wowhead/pets.js; see tools/wowhead/README.md).

A beast is kept when Wowhead lists it as tameable on its family's page and as using at least
one family ability rank that jsal.ui's SpellData knows. Each beast gets the pet's own spell IDs,
which the addon matches to Beast Training through SpellData's `families`.

Run: python -I tools/build_pets.py
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "data" / "pets" / "wowhead.json"
OUT = ROOT / "jsalUI" / "Training" / "TameData.lua"

sys.path.insert(0, str(ROOT / "tools" / "wowhead"))
from petspells import family_spells  # noqa: E402


def main():
    data = json.loads(SRC.read_text(encoding="utf-8"))
    known = family_spells()
    tameable = {npc for family in data["families"].values() for npc in family["tameable"]}
    beasts = {}
    unread = sorted(s for s in known if str(s) not in data["spells"])
    for spell, npcs in data["spells"].items():
        if int(spell) not in known:
            continue
        for npc in npcs:
            if npc in tameable:
                beasts.setdefault(npc, set()).add(int(spell))
    lines = [
        "-- Which beasts a hunter can tame carry which pet ability ranks, from Wowhead Forever (read on "
        f"{data['fetched']}).",
        "-- Generated by tools/build_pets.py; don't edit by hand.",
        "-- By creature ID: the pet's own spell IDs, which SpellData's `families` match to Beast Training.",
        "local _, ns = ...",
        "ns.TameData = {",
    ]
    row = []
    for npc in sorted(beasts):
        row.append(f"[{npc}] = {{ " + ", ".join(str(s) for s in sorted(beasts[npc])) + " },")
        if len(row) == 6:
            lines.append("    " + " ".join(row))
            row = []
    if row:
        lines.append("    " + " ".join(row))
    lines.append("}")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    empty = sorted(int(s) for s, npcs in data["spells"].items() if not npcs)
    print(f"{len(beasts)} tameable beasts with an ability, of {len(tameable)} tameable and {len(data['npcs'])} creatures read; "
          f"{len(data['families'])} families")
    if unread:
        print("Ability ranks not read yet: " + ", ".join(map(str, unread)))
    if empty:
        print("Ability ranks no creature uses: " + ", ".join(map(str, empty)))
    stray = sum(1 for npcs in data["spells"].values() for npc in npcs if npc not in tameable)
    print(f"{stray} uses by creatures that aren't tameable were left out")


if __name__ == "__main__":
    main()
