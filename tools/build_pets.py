"""Builds jsalUI/Training/TameData.lua: which beasts carry which pet ability rank, from Petopia's
WoW Forever ability lists (data/pets/petopia.json, read in the browser pane with
tools/petopia.js; see tools/wowhead/README.md).

Petopia names each rank ("Bite 2") and the beasts that have it. Each name and rank is matched
to the pet's own spell ID through the game's tables (data/spells) and the pet abilities in
jsalUI/Training/SpellData.lua's `families`, which the addon matches to Beast Training.

Run: python -I tools/build_pets.py
"""
import csv
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "data" / "pets" / "petopia.json"
OUT = ROOT / "jsalUI" / "Training" / "TameData.lua"


def pet_spells():
    """Every pet ability rank SpellData knows: {(name, rank number): the pet's spell ID}."""
    text = (ROOT / "jsalUI" / "Training" / "SpellData.lua").read_text(encoding="utf-8")
    start = text.index("        families = {")
    block = text[start:text.index("\n        },", start)]
    spells = {int(pet) for pet, _ in re.findall(r"\{ (\d+), (\d+), \d+, \d+ \}", block)}

    def table(name):
        with open(ROOT / "data" / "spells" / f"{name}.csv", newline="", encoding="utf-8") as f:
            return list(csv.DictReader(f))

    names = {int(r["ID"]): r["Name_lang"] for r in table("SpellName")}
    subtext = {int(r["ID"]): r["NameSubtext_lang"] for r in table("Spell")}
    by_key = {}
    for spell in sorted(spells):
        rank = re.search(r"(\d+)", subtext.get(spell) or "")
        by_key.setdefault((names.get(spell), int(rank.group(1)) if rank else 0), spell)
    return by_key


def main():
    data = json.loads(SRC.read_text(encoding="utf-8"))
    by_key = pet_spells()
    beasts, unknown, uses = {}, [], 0
    for key, rank in data["ranks"].items():
        name, number = key.rsplit("|", 1)
        if not rank["beasts"]:
            continue
        spell = by_key.get((name, int(number)))
        if not spell:
            unknown.append(key.replace("|", " "))
            continue
        for npc, _, _ in rank["beasts"]:
            beasts.setdefault(npc, set()).add(spell)
            uses += 1
    lines = [
        "-- Which beasts a hunter can tame carry which pet ability rank, from Petopia's WoW Forever lists",
        f"-- (wow-petopia.com, read on {data['fetched']}). Generated by tools/build_pets.py; don't edit by hand.",
        "-- By creature ID: the pet's own spell IDs, which SpellData's `families` match to Beast Training.",
        "local _, ns = ...",
        "ns.TameData = {",
    ]
    row = []
    for npc in sorted(beasts):
        row.append(f"[{npc}] = {{ " + ", ".join(str(s) for s in sorted(beasts[npc])) + " },")
        if len(row) == 8:
            lines.append("    " + " ".join(row))
            row = []
    if row:
        lines.append("    " + " ".join(row))
    lines.append("}")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"{len(beasts)} beasts, {uses} abilities on them, from {sum(1 for r in data['ranks'].values() if r['beasts'])} ranks")
    if unknown:
        print("Ranks Petopia lists that SpellData doesn't know (left out): " + ", ".join(unknown))


if __name__ == "__main__":
    main()
