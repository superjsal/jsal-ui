"""Builds jsalUI/TrainerData.lua: where each class and profession trainer stands.

From Wowhead Forever (data/trainers.json): each class's and profession's
trainers (from its page's Trainers tab), and each trainer's spot on the
game's own maps (uiMapID and x, y) from its NPC page. A trainer standing in
several spots keeps the first.

Run: python -I tools/build_trainers.py
"""

import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "data" / "trainers.json"
OUT = ROOT / "jsalUI" / "TrainerData.lua"


def lua_string(text):
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    data = json.loads(SRC.read_text(encoding="utf-8"))
    by_key = {}
    skipped = 0
    for npc_id, npc in data["npcs"].items():
        spot = None
        for zone in (data["spots"].get(npc_id) or {}).values():
            for entry in zone:
                if entry.get("uiMapId") and entry.get("coords"):
                    x, y = entry["coords"][0]
                    spot = (entry["uiMapId"], round(x / 100, 4), round(y / 100, 4))
                    break
            if spot:
                break
        if not spot:
            skipped += 1
            continue
        react = npc.get("react") or [None, None]
        alliance = (react[0] or 0) >= 0 and react[0] is not None
        horde = len(react) > 1 and react[1] is not None and react[1] >= 0
        for key in npc["keys"]:
            by_key.setdefault(key, []).append((int(npc_id), npc["name"], npc.get("tag") or "", spot, alliance, horde))
    lines = [
        "-- Where each class and profession trainer stands, from Wowhead Forever:",
        "-- the game's map ID, the spot on it, and which factions they'll train.",
        "-- Regenerated by the build, not by hand.",
        "local _, ns = ...",
        "",
        "ns.TrainerData = {",
    ]
    for key in sorted(by_key):
        lines.append(f"    {key} = {{")
        for npc_id, name, tag, (map_id, x, y), alliance, horde in sorted(by_key[key]):
            lines.append(f"        {{ npc = {npc_id}, name = {lua_string(name)}, tag = {lua_string(tag)}, "
                         f"map = {map_id}, x = {x}, y = {y}, a = {str(alliance).lower()}, h = {str(horde).lower()} }},")
        lines.append("    },")
    lines += ["}", ""]
    OUT.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"-> {OUT.relative_to(ROOT)}: {sum(len(v) for v in by_key.values())} entries over {len(by_key)} kinds, "
          f"{skipped} without a spot")


if __name__ == "__main__":
    main()
