"""Builds jsalUI/Games/DailyWordData.lua from the word lists in data/.

data/daily-word-answers.txt  the answers, any order, whitespace-separated
data/daily-word-guesses.txt  extra words accepted as guesses (optional)
data/daily-word-order.txt    the answers in the order they're played, one per
                             line. Written on the first run, then only ever
                             appended to: reordering it would change every
                             future day's word for everyone.

Run: python -I tools/build_words.py
"""

import pathlib
import random
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
DATA = ROOT / "data"
OUT = ROOT / "jsalUI" / "Games" / "DailyWordData.lua"
WORD = re.compile(r"^[a-z]{5}$")


def read_words(path):
    if not path.exists():
        return []
    words, bad = [], []
    for raw in path.read_text(encoding="utf-8").split():
        word = raw.strip().lower()
        (words if WORD.match(word) else bad).append(word)
    if bad:
        sys.exit(f"{path.name}: not five letters a-z: {', '.join(bad)}")
    return words


def encode(word, index):
    # Mirrors Answer() in DailyWord.lua: each letter shifted by its place.
    out = []
    for pos, letter in enumerate(word, start=1):
        shift = (index * 7 + pos * 3) % 26
        out.append(chr((ord(letter) - 97 + shift) % 26 + 97))
    return "".join(out)


def main():
    answers = sorted(set(read_words(DATA / "daily-word-answers.txt")))
    guesses = set(read_words(DATA / "daily-word-guesses.txt"))
    order_path = DATA / "daily-word-order.txt"
    order = read_words(order_path)
    if len(order) != len(set(order)):
        sys.exit("daily-word-order.txt has a word twice")

    new = [w for w in answers if w not in set(order)]
    random.Random(20261106 + len(order)).shuffle(new)
    order += new
    order_path.write_text("\n".join(order) + "\n", encoding="utf-8")

    extra = sorted(guesses - set(order))
    encoded = "".join(encode(w, i) for i, w in enumerate(order, start=1))
    lines = [
        "-- Daily Word's words, regenerated by the build from the word lists.",
        "-- The answers are scrambled so the list can't be read ahead.",
        "local _, ns = ...",
        "",
        "ns.DailyWordData = {",
        f'    answers = "{encoded}",',
        f'    guesses = "{"".join(extra)}",',
        "}",
        "",
    ]
    OUT.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"{len(order)} answers ({len(new)} new), {len(extra)} extra guesses -> {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
