"""Builds jsalUI/Journal/CooldownData.lua: the long profession cooldowns, for the Endgame page.

From the game's files for the Forever build, as CSV from wago.tools (data/spells and
data/professions):
  SkillLineAbility   each profession's recipes
  SpellName          their names
  SpellCooldowns     how long before a recipe can be made again
  SpellCategories    the cooldown a recipe shares with others (the transmutes share one)
  SpellEffect        the item a spell makes (effect 24, "create item")
  SpellReagents      what each recipe uses
  ItemEffect         an item's own spell and its cooldown
  ItemXItemEffect    which item each of those belongs to
  ItemSparse         item names

A cooldown is long when it's 20 hours or more: a "daily" one is 23 hours in the game's files.
Recipes that share a category are one cooldown, named by what their names share before the
colon ("Transmute"). An item counts when its own spell has a long cooldown and makes something a
profession's recipes use (the Salt Shaker, whose salt Leatherworking cures hides with); it belongs
to that profession.

Run: python -I tools/build_cooldowns.py 1.60.1.70959
"""

import csv
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SPELLS = ROOT / "data" / "spells"
PROF = ROOT / "data" / "professions"
OUT = ROOT / "jsalUI" / "Journal" / "CooldownData.lua"
LONG = 20 * 3600
PROFESSIONS = [171, 164, 333, 202, 165, 197, 186, 185, 129]


def rows(folder, name):
    with open(folder / f"{name}.csv", newline="", encoding="utf-8") as f:
        return list(csv.DictReader(f))


def main():
    build = sys.argv[1] if len(sys.argv) > 1 else "unknown"
    names = {int(r["ID"]): r["Name_lang"] for r in rows(SPELLS, "SpellName")}
    recipe_skill = {}
    for r in rows(SPELLS, "SkillLineAbility"):
        if int(r["SkillLine"]) in PROFESSIONS:
            recipe_skill.setdefault(int(r["Spell"]), int(r["SkillLine"]))
    waits = {}
    for r in rows(PROF, "SpellCooldowns"):
        if r["DifficultyID"] == "0":
            wait = max(int(r["CategoryRecoveryTime"] or 0), int(r["RecoveryTime"] or 0)) // 1000
            if wait > 0:
                waits[int(r["SpellID"])] = max(wait, waits.get(int(r["SpellID"]), 0))
    category = {int(r["SpellID"]): int(r["Category"]) for r in rows(PROF, "SpellCategories") if r["DifficultyID"] == "0"}

    # Recipes, grouped by the cooldown they share.
    groups = {}
    for spell, skill in recipe_skill.items():
        if waits.get(spell, 0) >= LONG:
            key = ("category", category[spell]) if spell in category else ("spell", spell)
            groups.setdefault(key, {"skill": skill, "spells": []})["spells"].append(spell)
    out = []
    for g in groups.values():
        spells = sorted(g["spells"])
        heads = {names.get(s, "").split(":")[0].strip() for s in spells}
        name = heads.pop() if len(spells) > 1 and len(heads) == 1 else names.get(spells[0], "")
        out.append({"name": name, "skill": g["skill"], "seconds": max(waits[s] for s in spells), "spells": spells})

    # Items with a long cooldown of their own, whose spell makes a profession's reagent.
    makes = {}
    for r in rows(PROF, "SpellEffect"):
        if r["Effect"] == "24" and r["DifficultyID"] == "0" and int(r["EffectItemType"] or 0) > 0:
            makes[int(r["SpellID"])] = int(r["EffectItemType"])
    used_by = {}
    for r in rows(PROF, "SpellReagents"):
        skill = recipe_skill.get(int(r["SpellID"]))
        if skill:
            for i in range(8):
                item = int(r[f"Reagent_{i}"])
                if item > 0:
                    used_by.setdefault(item, skill)
    effect_item = {int(r["ItemEffectID"]): int(r["ItemID"]) for r in rows(PROF, "ItemXItemEffect")}
    item_names = {int(r["ID"]): r["Display_lang"] for r in rows(PROF, "ItemSparse")}
    for r in rows(PROF, "ItemEffect"):
        wait = max(int(r["CoolDownMSec"] or 0), int(r["CategoryCoolDownMSec"] or 0)) // 1000
        spell, item = int(r["SpellID"]), effect_item.get(int(r["ID"]))
        made = makes.get(spell)
        if wait >= LONG and item and made in used_by and item_names.get(item):
            out.append({"name": item_names[item], "skill": used_by[made], "seconds": wait, "item": item})

    out.sort(key=lambda c: (PROFESSIONS.index(c["skill"]), c["name"]))
    lines = [
        "-- The long profession cooldowns, for the Endgame page: a day or so and more.",
        f"-- From the game's own tables (build {build}); regenerated by tools/build_cooldowns.py, not by hand.",
        "local _, ns = ...",
        "",
        "-- A cooldown: its name, the profession's skill line, the longest wait in seconds, and the",
        "-- recipes that share it (`spells`), or the item whose own cooldown it is (`item`).",
        "ns.CooldownData = {",
    ]
    for c in out:
        what = f'item = {c["item"]}' if "item" in c else "spells = { " + ", ".join(str(s) for s in c["spells"]) + " }"
        name = c["name"].replace("\\", "\\\\").replace('"', '\\"')
        lines.append(f'    {{ name = "{name}", skill = {c["skill"]}, seconds = {c["seconds"]}, {what} }},')
    lines += ["}", ""]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"-> {OUT.relative_to(ROOT)}: {len(out)} cooldowns")
    for c in out:
        print(f'  {c["name"]}: skill {c["skill"]}, {c["seconds"] / 3600:g}h, ' + (f'item {c["item"]}' if "item" in c else f'{len(c["spells"])} recipes'))


if __name__ == "__main__":
    main()
